#!/usr/bin/env python3
"""Generate the quality-policy test projects from projects/01_fault_count.yaml.

Not derived from a vendored example: these exercise SEM-QUAL-001 failure handling, which no
example covers. Each copies project 01, keeps only the ``tenant_isolation`` case (tenant_b
counts 2 faults) and adds a ``range`` check with maximum 1 to ``device.fault_count_7d``:

* ``quality_warn``       - severity warn: values publish unchanged, a warning is recorded;
* ``quality_quarantine`` - severity error, on_violation quarantine: QUALITY_QUARANTINED;
* ``quality_error``      - severity error, on_violation error: QUALITY_VIOLATION.

Goldens are reasoned by hand from the fixture (tenant_a 1 fault, tenant_b 2 faults).
"""
import copy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
BASE = yaml.safe_load((ROOT / "projects/01_fault_count.yaml").read_text(encoding="utf-8"))

VARIANTS = {
    "quality_warn": ("warn", "error", None),
    "quality_quarantine": ("error", "quarantine", "QUALITY_QUARANTINED"),
    "quality_error": ("error", "error", "QUALITY_VIOLATION"),
}


def build(name: str, severity: str, on_violation: str, code: str | None) -> dict:
    d = copy.deepcopy(BASE)
    d["metadata"]["id"] = f"featlas.test.{name}"
    d["metadata"]["name"] = f"Quality policy test: {name}"
    d["metadata"]["description"] = f"Project 01 with a range check (maximum 1, severity {severity}, on_violation {on_violation}) on device.fault_count_7d; generated by projects/quality/derive.py."
    f = d["features"][0]
    f["quality"] = {"checks": [{"kind": "finite", "severity": "error"}, {"kind": "range", "maximum": 1, "severity": severity}], "on_violation": on_violation}
    suite = d["acceptance_suites"][0]
    case = next(c for c in suite["cases"] if c["id"] == "tenant_isolation")
    case = copy.deepcopy(case)
    case["id"] = f"{name}_tenant_b_exceeds_range"
    case["name"] = f"{name}: tenant_b exceeds the range check"
    case["description"] = f"tenant_b has 2 faults against a range maximum of 1 (severity {severity}, on_violation {on_violation})."
    if code:
        case["expected"] = {"diagnostic": {"code": code}}
    suite["cases"] = [case]
    return d


for name, (sev, onv, code) in VARIANTS.items():
    out = ROOT / "projects/quality" / f"{name}.yaml"
    out.write_text("# Generated by projects/quality/derive.py; do not edit.\n" + yaml.safe_dump(build(name, sev, onv, code), sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(out.relative_to(ROOT))
