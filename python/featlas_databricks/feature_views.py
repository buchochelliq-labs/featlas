"""Databricks Feature Views for the features featlas maps exactly (``feature_api: feature_views``).

``databricks/<feature_set>/feature_views.json`` (generated by the adapter) says, per member
feature, whether it maps to a Feature View without semantic loss and, if not, why; features that
do not map stay on the Unity Catalog feature table that featlas publishes. This module turns the
mapped definitions into ``databricks.feature_engineering`` objects and compares their values with
featlas' own snapshot, so the choice of API never changes a feature's value silently.

* ``build(mapping)`` -> {feature id: Feature} (local objects; nothing is registered).
* ``training_values(fe, spark, features, keys, as_of)`` -> point-in-time values at ``as_of`` via
  ``create_training_set`` (read-only compute).
* ``compare(mapping, fv_rows, featlas_rows, keys)`` -> per feature: rows compared, mismatches
  (null-safe, numeric tolerance 1e-9 relative), and how empty windows were represented.
* ``register(fe, features, catalog, schema)`` registers them in Unity Catalog (resource creation;
  call only with explicit authorization).
"""

from __future__ import annotations

from datetime import datetime, timedelta
from typing import Any


def mapped(mapping: dict) -> list[dict]:
    return [f for f in mapping["features"] if f["api"] == "feature_views"]


def build(mapping: dict) -> dict[str, Any]:
    from databricks.feature_engineering.entities import (  # type: ignore
        AggregationFunction,
        Avg,
        Count,
        DeltaTableSource,
        Feature,
        First,
        Last,
        Max,
        Min,
        RollingWindow,
        Sum,
    )

    ops = {"Sum": Sum, "Avg": Avg, "Count": Count, "Min": Min, "Max": Max, "Last": Last, "First": First}
    out = {}
    for f in mapped(mapping):
        d = f["definition"]
        src = DeltaTableSource(catalog_name=d["source"]["catalog_name"], schema_name=d["source"]["schema_name"], table_name=d["source"]["table_name"], filter_condition=d["source"]["filter_condition"])
        window = RollingWindow(window_duration=timedelta(seconds=d["time_window"]["window_duration_seconds"]))
        fn = AggregationFunction(ops[d["function"]["operator"]](input=d["function"]["input"]), window)
        out[f["feature"]] = Feature(source=src, entity=d["entity"], timeseries_column=d["timeseries_column"], function=fn, name=d["name"])
    return out


def training_values(fe, spark, features: dict[str, Any], keys: list[dict], as_of: datetime, timeseries_column: str) -> list[dict]:
    """Feature View values for entity ``keys`` evaluated at ``as_of`` (the spine's timeseries)."""
    if not keys:
        return []
    spine = spark.createDataFrame([{**k, timeseries_column: as_of} for k in keys])
    ts = fe.create_training_set(df=spine, features=list(features.values()), label=None)
    return [r.asDict() for r in ts.load_df().collect()]


def _same(a: Any, b: Any) -> bool:
    if a is None or b is None:
        return a is None and b is None
    if isinstance(a, (int, float)) and isinstance(b, (int, float)) and not isinstance(a, bool):
        return abs(float(a) - float(b)) <= 1e-9 * max(1.0, abs(float(b)))
    return a == b


def compare(mapping: dict, fv_rows: list[dict], featlas_rows: list[dict], keys: list[str]) -> dict:
    """Per mapped feature: equal values except where the spec's empty-window value differs from a
    Feature View null (reported separately, never counted as equal)."""
    fv = {tuple(r[k] for k in keys): r for r in fv_rows}
    report = {}
    for f in mapped(mapping):
        col = f["definition"]["name"]
        state_col = next((c for c in featlas_rows[0] if c == f"{col}_state"), None) if featlas_rows else None
        mism, empty_as_null, compared = [], 0, 0
        for r in featlas_rows:
            k = tuple(r[x] for x in keys)
            got = fv.get(k, {}).get(col)
            want = r.get(col)
            compared += 1
            if _same(got, want):
                continue
            if got is None and state_col and r.get(state_col) == "empty":
                empty_as_null += 1
                continue
            mism.append({"keys": dict(zip(keys, k)), "feature_view": got, "featlas": want})
        report[f["feature"]] = {"column": col, "rows_compared": compared, "mismatches": mism, "empty_window_served_as_null": empty_as_null, "empty_window_spec": f["definition"]["empty_window"]}
    return report


def register(fe, features: dict[str, Any], catalog: str, schema: str) -> list[str]:
    return [fe.register_feature(feature=f, catalog_name=catalog, schema_name=schema).name for f in features.values()]
